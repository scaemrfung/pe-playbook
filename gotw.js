/* Games of the Week page: shows this week's 3 games for Grades 1–3 and 3 games for Grades 4–6 (by date in America/Edmonton, switching on Monday),
   a "Coming up next week" preview, and arrows to browse other weeks. Data: games-of-the-week-data.js
   (generated by tools/build.js from games-of-the-week.json). Test a date with ?today=YYYY-MM-DD. */
(function () {
  function run() {
    var D = window.GAMES_OF_THE_WEEK, SY = window.SCHOOL_YEAR, box = document.getElementById("gotw-now");
    if (!D || !box || !D.weeks || !D.weeks.length) return;
    var DAY = 864e5;
    function parse(s) { var m = /^(\d{4})-(\d{2})-(\d{2})$/.exec(s); return m ? Date.UTC(+m[1], +m[2] - 1, +m[3]) : null; }
    function iso(t) { return new Date(t).toISOString().slice(0, 10); }
    function mondayOf(k) { var t = parse(k), d = new Date(t).getUTCDay(); return iso(t - ((d + 6) % 7) * DAY); }
    function esc(s) { return String(s == null ? "" : s).replace(/[&<>"]/g, function (c) { return { "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[c]; }); }
    var MON = ["Jan", "Feb", "Mar", "Apr", "May", "June", "July", "Aug", "Sept", "Oct", "Nov", "Dec"];
    var DOW = ["Sunday", "Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday"];
    function longDay(k) { var d = new Date(parse(k)); return DOW[d.getUTCDay()] + " " + MON[d.getUTCMonth()] + " " + d.getUTCDate(); }

    var today = SY && SY.todayISO ? SY.todayISO() : iso(Date.now());
    var mon = mondayOf(today);
    var W = D.weeks;
    var idx = -1, mode = "week", brk = null;
    for (var i = 0; i < W.length; i++) if (W[i].monday === mon) idx = i;
    if (idx < 0) {
      if (today < W[0].start) { mode = "before"; idx = 0; }
      else if (today > W[W.length - 1].end) { mode = "summer"; idx = -1; }
      else {
        D.breaks.forEach(function (b) { if (b.start <= mon && mon <= b.end) brk = b; });
        for (var j = 0; j < W.length; j++) if (W[j].monday > mon) { idx = j; break; }
        mode = "break";
      }
    }
    var home = idx, view = idx;
    var pw = document.getElementById("gotw-print-week");
    if (pw && idx >= 0) pw.href = "games-of-the-week-print.html?week=" + W[idx].n + "&print=1";

    function cardsHtml(picks) {
      return '<ol class="gotw-cards">' + picks.map(function (p, n) {
        return '<li class="gotw-card"><span class="gotw-num">' + (n + 1) + '</span><div><h4><a href="' + esc(p.href) + '">' + esc(p.name) + "</a></h4>" +
          '<p class="gotw-why">' + esc(p.reason) + "</p>" +
          (p.equipment ? '<p class="gotw-kit"><strong>Equipment:</strong> ' + esc(p.equipment) + "</p>" : "") +
          '<p class="gotw-page-line"><a href="' + esc(p.href) + '">Open the full card</a> <span class="gotw-page">' + esc(p.page) + "</span></p></div></li>";
      }).join("") + "</ol>";
    }
    function picksHtml(w) {
      return (w.bands || []).map(function (b) {
        return '<section class="gotw-band gotw-band-' + esc(b.id) + '" aria-label="' + esc(b.label) + '"><h3 class="gotw-band-title">' + esc(b.label) +
          (b.blurb ? ' <span class="gotw-band-blurb">' + esc(b.blurb) + "</span>" : "") + "</h3>" + cardsHtml(b.picks) + "</section>";
      }).join("");
    }
    function nextOf(i) { return i + 1 < W.length ? W[i + 1] : null; }
    function breakBetween(a, b) {
      var out = null;
      D.breaks.forEach(function (x) { if (x.start > a.end && (!b || x.start < b.start)) out = out || x; });
      return out;
    }
    function render() {
      var h = "";
      if (mode === "summer" && view < 0) {
        box.innerHTML = '<div class="panel gotw-current"><h2>The ' + esc(D.year) + ' school year is over</h2><p class="meta">Have a great summer. Browse any week below to plan ahead.</p></div>';
        return;
      }
      var w = W[view], isHome = view === home;
      var kicker = isHome ? (mode === "break" ? "Back after the break" : mode === "before" ? "First week of school" : "This week") : (w.monday < mon ? "Earlier week" : "Later week");
      if (isHome && mode === "break" && brk) {
        h += '<div class="panel gotw-break"><h2>' + esc(brk.name) + " (" + esc(brk.range) + ")</h2><p>No school this week, so no games. Enjoy the break! " +
          "Here’s what’s ready for " + esc(longDay(w.start)) + ".</p></div>";
      }
      h += '<div class="panel gotw-current"><p class="kicker">' + kicker + "</p>" +
        "<h2>Week " + w.n + " · " + esc(w.range) + '</h2><p class="gotw-sub"><span class="pill gotw-unit-pill">' + esc(w.month) + ": " + esc(w.unit) + "</span>" +
        (w.note ? ' <span class="gotw-wnote">' + esc(w.note) + "</span>" : "") + "</p>" + picksHtml(w) +
        '<p class="gotw-nav no-print">' +
        (view > 0 ? '<button type="button" class="btn-ghost" data-go="-1">← Earlier week</button>' : "") +
        (!isHome && home >= 0 ? '<button type="button" class="btn-ghost" data-go="home">Back to this week</button>' : "") +
        (view < W.length - 1 ? '<button type="button" class="btn-ghost" data-go="1">Later week →</button>' : "") +
        '<a class="btn gotw-print-btn" href="games-of-the-week-print.html?week=' + w.n + '&amp;print=1">' + (isHome ? "Print this week" : "Print Week " + w.n) + "</a></p></div>";
      var nx = nextOf(view);
      if (nx) {
        var gap = breakBetween(w, nx);
        h += '<div class="panel gotw-next"><p class="kicker">Coming up next week</p><h2>Week ' + nx.n + " · " + esc(nx.range) +
          (gap ? ' <span class="gotw-wnote">after ' + esc(gap.name) + " (" + esc(gap.range) + ")</span>" : "") + "</h2>" +
          '<p class="gotw-sub"><span class="pill gotw-unit-pill">' + esc(nx.month) + ": " + esc(nx.unit) + "</span></p>" +
          '<div class="gotw-next-bands">' + (nx.bands || []).map(function (b) {
            return '<div class="gotw-next-band gotw-band-' + esc(b.id) + '"><h3 class="gotw-band-title">' + esc(b.label) + '</h3><ul class="gotw-next-list">' + b.picks.map(function (p) {
              return '<li><a href="' + esc(p.href) + '">' + esc(p.name) + "</a> <span class=\"gotw-why\">" + esc(p.reason) + "</span></li>";
            }).join("") + "</ul></div>";
          }).join("") + "</div></div>";
      } else {
        h += '<div class="panel gotw-next"><p class="kicker">Coming up next week</p><p class="meta">That’s the last week of the school year.</p></div>';
      }
      box.innerHTML = h;
      box.querySelectorAll("[data-go]").forEach(function (b) {
        b.addEventListener("click", function () {
          var g = b.getAttribute("data-go");
          view = g === "home" ? home : Math.max(0, Math.min(W.length - 1, view + (+g)));
          render();
          box.scrollIntoView({ behavior: "smooth", block: "start" });
        });
      });
    }
    render();

    // Mark this week in the year list and open its month.
    if (home >= 0) {
      var cur = document.getElementById("week-" + W[home].n);
      if (cur) {
        cur.classList.add("gotw-is-current");
        var h3 = cur.querySelector("h3");
        if (h3) h3.insertAdjacentHTML("beforeend", ' <span class="this-week-pill">' + (mode === "week" ? "This week" : "Next up") + "</span>");
        var det = cur.closest("details");
        if (det) det.open = true;
      }
    }
    // Opening a #week-N link opens its month.
    function openHash() {
      var el = location.hash && document.getElementById(location.hash.slice(1));
      var det = el && el.closest && el.closest("details");
      if (det) { det.open = true; el.scrollIntoView(); }
    }
    openHash();
    window.addEventListener("hashchange", openHash);
  }
  if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", run); else run();
})();
