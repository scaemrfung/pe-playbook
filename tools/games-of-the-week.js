/*
 * Games of the Week (games-of-the-week.html) — called by tools/build.js.
 *
 * games-of-the-week.json holds 3 picks per school week (month -> in-month week -> [name, reason]).
 * This module matches every school week in school-year.js to its picks, looks up each game's card
 * (New Games, Warm Up Games or Big-Group Games) for the link and equipment, and returns:
 *   js    games-of-the-week-data.js (the full year; the page picks the current week by date)
 *   html  the no-JS fallback: every week of the year, baked into games-of-the-week.html
 * Breaks (school-year.js BREAKS) are listed too, so the page can show a friendly break note.
 */
"use strict";
const fs = require("fs");
const path = require("path");

module.exports = function gamesOfTheWeek({ ROOT, W, SY, gameHref, gslug, esc, anchorOk, detailFor }) {
  const src = JSON.parse(fs.readFileSync(path.join(ROOT, "games-of-the-week.json"), "utf8"));
  const warnings = [];
  const NG = (W.NEW_GAMES && W.NEW_GAMES.games) || [];
  const WU = W.WARMUP_NOGYM_GAMES || [];
  const PAGE = { "new-games.html": "New Games", "warmup-nogym.html": "Warm Up Games", "games.html": "Big-Group Games", "dodgeball.html": "Dodgeball" };
  const key = (s) => String(s || "").toLowerCase().replace(/[’']/g, "'").trim();
  const shortEquip = (e) => {
    let s = Array.isArray(e) ? e.join("; ") : String(e || "");
    s = s.replace(/<[^>]+>/g, "").replace(/\s+/g, " ").trim();
    if (/^none\.?$/i.test(s)) return "None";
    return s.length > 150 ? s.slice(0, 147).replace(/[\s,;·]+\S*$/, "") + "…" : s;
  };

  function lookup(name) {
    const k = key(name);
    const n = NG.find((g) => key(g.name) === k);
    if (n) return { href: `new-games.html#${n.id}`, equipment: shortEquip(n.equipment) };
    const w = WU.find((g) => key(g.title) === k);
    if (w) return { href: `warmup-nogym.html#${gslug(w.title)}`, equipment: shortEquip(w.equipment) };
    const d = detailFor(name);
    if (d) return { href: gameHref(d.name), equipment: shortEquip(d.equipment) };
    return null;
  }

  const weeks = [];
  const seenInMonth = {};
  SY.peWeekList().forEach((w) => {
    const list = ((src.picks || {})[w.month] || {})[String(w.w)];
    if (!list) { warnings.push(`games-of-the-week.json: no picks for ${w.month} week ${w.w} (${w.range})`); return; }
    if (list.length !== 3) warnings.push(`games-of-the-week.json: ${w.month} week ${w.w} has ${list.length} picks (expected 3)`);
    const picks = list.map(([name, reason]) => {
      const hit = lookup(name);
      if (!hit) { warnings.push(`games-of-the-week.json: "${name}" (${w.month} week ${w.w}) has no card on the site`); return null; }
      if (!anchorOk(hit.href)) warnings.push(`games-of-the-week.json: "${name}" links to ${hit.href}, which has no matching card`);
      const seen = (seenInMonth[w.month] = seenInMonth[w.month] || new Set());
      if (seen.has(key(name))) warnings.push(`games-of-the-week.json: "${name}" is picked twice in ${w.month}`);
      seen.add(key(name));
      return { name, reason, href: hit.href, page: PAGE[hit.href.split("#")[0]] || "", equipment: hit.equipment };
    }).filter(Boolean);
    weeks.push({ n: w.schoolWeek, monday: SY.weeks.find((x) => x.n === w.schoolWeek).monday, start: w.start, end: w.end,
      range: w.range, month: w.month, w: w.w, unit: (src.units || {})[w.month] || "", note: w.note || "", picks });
  });
  const breaks = (SY.breaks || []).map((b) => ({ name: b.name, start: b.start, end: b.end, range: b.range }));

  const js = `/* Generated by tools/build.js from games-of-the-week.json — do not edit by hand.
   Games of the Week: 3 games per school week (${SY.calendar.label}). Weeks switch on Monday (America/Edmonton). */
window.GAMES_OF_THE_WEEK = ${JSON.stringify({ year: SY.calendar.label, weeks, breaks }, null, 1)};
`;

  // ---- no-JS fallback: the whole year, grouped by month (also the "browse other weeks" list)
  const pickLi = (p) => `            <li class="gotw-pick">
              <a class="gotw-name" href="${esc(p.href)}">${esc(p.name)}</a> <span class="gotw-page">${esc(p.page)}</span>
              <span class="gotw-why">${esc(p.reason)}</span>${p.equipment ? `\n              <span class="gotw-kit"><strong>Equipment:</strong> ${esc(p.equipment)}</span>` : ""}
            </li>`;
  const months = [];
  weeks.forEach((w) => { let m = months.find((x) => x.name === w.month); if (!m) months.push((m = { name: w.month, unit: w.unit, weeks: [] })); m.weeks.push(w); });
  const breakAfter = (w) => breaks.filter((b) => b.start > w.end && !weeks.some((x) => x.start > w.end && x.start < b.start));
  const html = months.map((m) => `      <details class="gotw-month" id="gotw-${m.name.toLowerCase()}">
        <summary><span class="gotw-month-name">${esc(m.name)}</span> <span class="gotw-unit">${esc(m.unit)}</span> <span class="gotw-count">${m.weeks.length} week${m.weeks.length === 1 ? "" : "s"}</span></summary>
${m.weeks.map((w) => `        <section class="gotw-week" id="week-${w.n}" data-monday="${w.monday}">
          <h3>Week ${w.n} · ${esc(w.range)}${w.note ? ` <span class="gotw-wnote">${esc(w.note)}</span>` : ""}</h3>
          <ol class="gotw-list">
${w.picks.map(pickLi).join("\n")}
          </ol>
        </section>${breakAfter(w).map((b) => `
        <p class="gotw-break-row">${esc(b.name)} (${esc(b.range)}): no school, no games this week.</p>`).join("")}`).join("\n")}
      </details>`).join("\n");

  const report = `games-of-the-week-data.js: ${weeks.length} school weeks, ${weeks.reduce((a, w) => a + w.picks.length, 0)} picks, ${breaks.length} breaks`;
  return { js, html, warnings, report, weeks };
};
