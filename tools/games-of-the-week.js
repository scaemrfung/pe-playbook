/*
 * Games of the Week (games-of-the-week.html) — called by tools/build.js.
 *
 * games-of-the-week.json holds, for every school week, 3 picks for Grades 1–3 (g13) and 3 different picks for Grades 4–6
 * (g46): month -> in-month week -> { g13: [[name, reason] ×3], g46: [...] }. Mr. Fung, Nov 1 2026: "revise the Games of the
 * Week page with 3 games for Grades 1-3 and 3 games for Grades 4-6".
 * This module matches every school week in school-year.js to its picks, looks up each game's card
 * (New Games, Warm Up Games or Big-Group Games) for the link and equipment, and returns:
 *   js    games-of-the-week-data.js (the full year; the page picks the current week by date)
 *   html  the no-JS fallback: every week of the year, baked into games-of-the-week.html
 * Breaks (school-year.js BREAKS) are listed too, so the page can show a friendly break note.
 */
"use strict";
const fs = require("fs");
const path = require("path");

module.exports = function gamesOfTheWeek({ ROOT, W, SY, gameHref, gslug, esc, anchorOk, detailFor }) {
  const src = JSON.parse(fs.readFileSync(path.join(ROOT, "games-of-the-week.json"), "utf8"));
  const warnings = [];
  const NG = (W.NEW_GAMES && W.NEW_GAMES.games) || [];
  const WU = W.WARMUP_NOGYM_GAMES || [];
  const PAGE = { "new-games.html": "New Games", "warmup-nogym.html": "Warm Up Games", "games.html": "Big-Group Games", "dodgeball.html": "Dodgeball" };
  const key = (s) => String(s || "").toLowerCase().replace(/[’']/g, "'").trim();
  const shortEquip = (e) => {
    let s = Array.isArray(e) ? e.join("; ") : String(e || "");
    s = s.replace(/<[^>]+>/g, "").replace(/\s+/g, " ").trim();
    if (/^none\.?$/i.test(s)) return "None";
    return s.length > 150 ? s.slice(0, 147).replace(/[\s,;·]+\S*$/, "") + "…" : s;
  };

  function lookup(name) {
    const k = key(name);
    const n = NG.find((g) => key(g.name) === k);
    if (n) return { href: `new-games.html#${n.id}`, equipment: shortEquip(n.equipment) };
    const w = WU.find((g) => key(g.title) === k);
    if (w) return { href: `warmup-nogym.html#${gslug(w.title)}`, equipment: shortEquip(w.equipment) };
    const d = detailFor(name);
    if (d) return { href: gameHref(d.name), equipment: shortEquip(d.equipment) };
    return null;
  }

  const BANDS = src.bands || [{ id: "g13", label: "Grades 1–3" }, { id: "g46", label: "Grades 4–6" }];
  const weeks = [];
  const seenInMonth = {};
  SY.peWeekList().forEach((w) => {
    const entry = ((src.picks || {})[w.month] || {})[String(w.w)];
    if (!entry) { warnings.push(`games-of-the-week.json: no picks for ${w.month} week ${w.w} (${w.range})`); return; }
    const bands = BANDS.map((b) => {
      const list = entry[b.id] || [];
      if (list.length !== 3) warnings.push(`games-of-the-week.json: ${w.month} week ${w.w} ${b.label} has ${list.length} picks (expected 3)`);
      const picks = list.map(([name, reason]) => {
        const hit = lookup(name);
        if (!hit) { warnings.push(`games-of-the-week.json: "${name}" (${w.month} week ${w.w}, ${b.label}) has no card on the site`); return null; }
        if (!anchorOk(hit.href)) warnings.push(`games-of-the-week.json: "${name}" links to ${hit.href}, which has no matching card`);
        const sk = w.month + "|" + b.id, seen = (seenInMonth[sk] = seenInMonth[sk] || new Set());
        if (seen.has(key(name))) warnings.push(`games-of-the-week.json: "${name}" is picked twice for ${b.label} in ${w.month}`);
        seen.add(key(name));
        return { name, reason, href: hit.href, page: PAGE[hit.href.split("#")[0]] || "", equipment: hit.equipment };
      }).filter(Boolean);
      return { id: b.id, label: b.label, blurb: b.blurb || "", picks };
    });
    const both = bands[0].picks.filter((p) => bands.slice(1).some((b) => b.picks.some((q) => key(q.name) === key(p.name))));
    both.forEach((p) => warnings.push(`games-of-the-week.json: "${p.name}" is in both grade bands in ${w.month} week ${w.w}`));
    weeks.push({ n: w.schoolWeek, monday: SY.weeks.find((x) => x.n === w.schoolWeek).monday, start: w.start, end: w.end,
      range: w.range, month: w.month, w: w.w, unit: (src.units || {})[w.month] || "", note: w.note || "", bands });
  });
  const breaks = (SY.breaks || []).map((b) => ({ name: b.name, start: b.start, end: b.end, range: b.range }));

  const js = `/* Generated by tools/build.js from games-of-the-week.json — do not edit by hand.
   Games of the Week: 3 games for Grades 1–3 and 3 for Grades 4–6 per school week (${SY.calendar.label}). Weeks switch on Saturday (America/Edmonton). */
window.GAMES_OF_THE_WEEK = ${JSON.stringify({ year: SY.calendar.label, weeks, breaks }, null, 1)};
`;

  // ---- no-JS fallback: the whole year, grouped by month (also the "browse other weeks" list)
  const pickLi = (p) => `            <li class="gotw-pick">
              <a class="gotw-name" href="${esc(p.href)}">${esc(p.name)}</a> <span class="gotw-page">${esc(p.page)}</span>
              <span class="gotw-why">${esc(p.reason)}</span>${p.equipment ? `\n              <span class="gotw-kit"><strong>Equipment:</strong> ${esc(p.equipment)}</span>` : ""}
            </li>`;
  const months = [];
  weeks.forEach((w) => { let m = months.find((x) => x.name === w.month); if (!m) months.push((m = { name: w.month, unit: w.unit, weeks: [] })); m.weeks.push(w); });
  const breakAfter = (w) => breaks.filter((b) => b.start > w.end && !weeks.some((x) => x.start > w.end && x.start < b.start));
  const html = months.map((m) => `      <details class="gotw-month" id="gotw-${m.name.toLowerCase()}">
        <summary><span class="gotw-month-name">${esc(m.name)}</span> <span class="gotw-unit">${esc(m.unit)}</span> <span class="gotw-count">${m.weeks.length} week${m.weeks.length === 1 ? "" : "s"}</span></summary>
${m.weeks.map((w) => `        <section class="gotw-week" id="week-${w.n}" data-monday="${w.monday}">
          <h3>Week ${w.n} · ${esc(w.range)}${w.note ? ` <span class="gotw-wnote">${esc(w.note)}</span>` : ""}</h3>
${w.bands.map((b) => `          <h4 class="gotw-band-h gotw-band-${b.id}">${esc(b.label)}</h4>
          <ol class="gotw-list">
${b.picks.map(pickLi).join("\n")}
          </ol>`).join("\n")}
        </section>${breakAfter(w).map((b) => `
        <p class="gotw-break-row">${esc(b.name)} (${esc(b.range)}): no school, no games this week.</p>`).join("")}`).join("\n")}
      </details>`).join("\n");

  // ---- printable sheets (Mr. Fung, Oct 31 2026: "have a printable version of the games of the week document")
  // One page per school week: dates, unit, and for each game its type, equipment, set-up, how we play, cues and
  // key safety, copied from the game's existing card. Written to games-of-the-week-print.html (print / "Print this
  // week"), and to Games-of-the-Week-<year>.pdf / .docx by tools/gotw-print.py (run from build.js).
  const SITE = "https://scaemrfung.github.io/pe-playbook/";
  const EXTRAS = W.GAME_EXTRAS || {};
  const TYPE_LABELS = { tag: "Tag & chase", invasion: "Invasion & team", target: "Target & send", strike: "Strike & field",
    relay: "Relays & stations", loco: "Locomotor & listen", coop: "Cooperative & circus", fitness: "Fitness & landings" };
  let TYPE_WORDS = {};
  try {
    const m = /const TYPE_WORDS = (\{[\s\S]*?\n\s*\});/.exec(fs.readFileSync(path.join(ROOT, "app.js"), "utf8"));
    if (m) TYPE_WORDS = Function(`"use strict"; return (${m[1]});`)();
  } catch (e) { warnings.push("games-of-the-week print: could not read game types from app.js (" + e.message + ")"); }
  const typeOf = (g) => {
    if (g.type && TYPE_LABELS[g.type]) return g.type;
    const low = String(g.name || "").toLowerCase();
    for (const t of Object.keys(TYPE_LABELS)) for (const w of TYPE_WORDS[t] || []) if (low.includes(w)) return t;
    return "loco";
  };
  const clean = (s) => String(s == null ? "" : s).replace(/<[^>]+>/g, "").replace(/&amp;/g, "&").replace(/\s+/g, " ").trim();
  const list = (a) => [].concat(a || []).map(clean).filter(Boolean);
  // The house-rule sentences every card repeats go once in the page footer instead.
  const BOILER = [/No elimination: a sit is a stretch, a jail, a hospital, or a role swap, then back in\./i, /Freeze on the whistle\./i,
    /Watch a demo or clip before the first play if you have one\./i, /A miss is a short task and you stay in\./i,
    /Extra players get a job \([^)]*\)\./i];
  const safetyText = (s) => { let t = clean(s); BOILER.forEach((re) => { t = t.replace(re, ""); }); return t.replace(/\s+/g, " ").trim(); };
  const equipText = (e) => { const s = clean(Array.isArray(e) ? e.join("; ") : e); return /^none\.?$/i.test(s) ? "None" : s; };
  // Day-off notes keep the date but drop the day's name (no holiday names on the printables).
  const printNote = (n) => clean(n).replace(/\s*\([^)]*\)/g, "");
  const printBreak = (name) => /christmas/i.test(name) ? "Winter Break" : name;

  function sheetFor(p) {
    const k = key(p.name);
    const n = NG.find((g) => key(g.name) === k);
    if (n) return { type: n.typeLabel || TYPE_LABELS[n.type] || "", grades: clean(n.grades), equipment: equipText(n.equipment),
      setup: clean(n.setup), how: list(n.how), cues: list(n.cues).slice(0, 4), safety: safetyText(n.safety) };
    const w = WU.find((g) => key(g.title) === k);
    if (w) {
      const steps = list(w.how);
      return { type: "Warm-up", grades: clean(w.grades), equipment: equipText(w.equipment),
        setup: steps.filter((x) => /^set-?up:/i.test(x)).map((x) => x.replace(/^set-?up:\s*/i, "")).join(" "),
        how: steps.filter((x) => !/^set-?up:/i.test(x)).map((x) => x.replace(/^play:\s*/i, "")),
        cues: [], safety: safetyText(w.safety) };
    }
    const d = detailFor(p.name);
    if (d) {
      const x = EXTRAS[d.name] || {};
      return { type: TYPE_LABELS[typeOf(d)] || "", grades: "", equipment: equipText(d.equipment), setup: clean(d.setup),
        how: list(d.play), cues: list(x.cues).slice(0, 4), safety: safetyText(d.safety) };
    }
    return null;
  }
  const MONS = ["Jan", "Feb", "Mar", "Apr", "May", "June", "July", "Aug", "Sept", "Oct", "Nov", "Dec"];
  const DAYS = ["Sun", "Mon", "Tue", "Wed", "Thu", "Fri", "Sat"];
  const longDate = (s) => { const d = new Date(s + "T12:00:00Z"); return `${DAYS[d.getUTCDay()]} ${MONS[d.getUTCMonth()]} ${d.getUTCDate()}`; };
  const yearOf = (s) => s.slice(0, 4);
  const sheets = weeks.map((w) => ({
    n: w.n, month: w.month, unit: w.unit, range: w.range,
    dates: w.start === w.end ? `${longDate(w.start)}, ${yearOf(w.start)}` : `${longDate(w.start)} – ${longDate(w.end)}, ${yearOf(w.end)}`,
    note: printNote(w.note),
    breakAfter: breakAfter(w).map((b) => ({ name: printBreak(b.name), range: b.range })),
    bands: w.bands.map((b) => ({ id: b.id, label: b.label, games: b.picks.map((p) => {
      const s = sheetFor(p);
      if (!s) warnings.push(`games-of-the-week print: no card text for "${p.name}"`);
      if (s && !s.how.length) warnings.push(`games-of-the-week print: "${p.name}" has no how-to-play steps`);
      // a step that only repeats the set-up text (some merged cards) is dropped
      if (s && s.setup) { const su = key(s.setup); s.how = s.how.filter((x) => !su.includes(key(x).replace(/\.$/, ""))); }
      return Object.assign({ name: p.name, reason: p.reason, url: SITE + p.href, page: p.page }, s || {});
    }) })),
  }));
  const printMonths = [];
  sheets.forEach((w) => { let m = printMonths.find((x) => x.name === w.month); if (!m) printMonths.push((m = { name: w.month, unit: w.unit, weeks: [] })); m.weeks.push(w.n); });
  const FILE = `Games-of-the-Week-${SY.calendar.label.replace(/[–—]/g, "-")}`;
  const HOUSE = "House rules for every game: no elimination (a sit is a short task, then back in), freeze on the whistle, extra players get a job, and show a demo before the first play.";
  const printData = { title: `Games of the Week ${SY.calendar.label}`, year: SY.calendar.label, teacher: "Mr. Fung", school: "SCA Elementary PE",
    file: FILE, site: SITE, house: HOUSE, months: printMonths, weeks: sheets, bands: BANDS.map((b) => ({ id: b.id, label: b.label })) };

  const e = esc;
  const gameHtml = (g, i) => `        <article class="gp-game">
          <h3><span class="gp-num">${i + 1}</span> <a href="${e(g.url)}">${e(g.name)}</a></h3>
          <p class="gp-meta">${[g.type, g.grades ? "Grades " + g.grades : "", g.page].filter(Boolean).map(e).join(" · ")}</p>
          <p class="gp-why">${e(g.reason)}</p>
          <p><strong>Equipment:</strong> ${e(g.equipment || "See the card")}</p>${g.setup ? `
          <p><strong>Set-up:</strong> ${e(g.setup)}</p>` : ""}
          <div class="gp-how"><strong>How we play:</strong>
            <ol>${(g.how || []).map((x) => `<li>${e(x)}</li>`).join("")}</ol>
          </div>${g.cues && g.cues.length ? `
          <p><strong>Cues:</strong> ${g.cues.map(e).join(" · ")}</p>` : ""}${g.safety ? `
          <p class="gp-safety"><strong>Safety:</strong> ${e(g.safety)}</p>` : ""}
        </article>`;
  // one page per grade band: Week N Grades 1–3, then Week N Grades 4–6
  const sheetHtml = (w) => w.bands.map((b, bi) => `      <section class="gp-sheet gp-week gp-${b.id}" id="week-${w.n}${bi ? "-" + b.id : ""}" data-week="${w.n}" data-band="${b.id}">
        <header class="gp-band">
          <p class="gp-kicker">Games of the Week · ${e(SY.calendar.label)} · Mr. Fung</p>
          <h2>Week ${w.n} · ${e(w.dates)} <span class="gp-grades">${e(b.label)}</span></h2>
          <p class="gp-unit">${e(w.month)}: ${e(w.unit)}${w.note ? ` <span class="gp-note">${e(w.note)}</span>` : ""}</p>
        </header>
${b.games.map(gameHtml).join("\n")}
${bi === w.bands.length - 1 ? w.breakAfter.map((x) => `        <p class="gp-break">Next: ${e(x.name)} (${e(x.range)}). No school, no games that week.</p>`).join("\n") : ""}
        <p class="gp-foot">${e(HOUSE)}</p>
      </section>`).join("\n");
  const contents = printMonths.map((m) => `        <tr class="gp-mrow"><th colspan="${2 + BANDS.length}">${e(m.name)} <span>${e(m.unit)}</span></th></tr>
${m.weeks.map((n) => { const w = sheets[n - 1] && sheets[n - 1].n === n ? sheets[n - 1] : sheets.find((x) => x.n === n);
    return `        <tr><td><a href="#week-${w.n}">Week ${w.n}</a></td><td>${e(w.range)}</td>${w.bands.map((b) => `<td>${b.games.map((g) => e(g.name)).join(" · ")}</td>`).join("")}</tr>` +
      w.breakAfter.map((b) => `\n        <tr class="gp-brow"><td colspan="${2 + BANDS.length}">${e(b.name)} (${e(b.range)}): no school</td></tr>`).join(""); }).join("\n")}`).join("\n");
  const printHtml = `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="utf-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1" />
  <title>Games of the Week ${e(SY.calendar.label)} · Printable · Mr. Fung</title>
  <meta name="description" content="Printable Games of the Week: for every school week, one page of 3 games for Grades 1–3 and one page of 3 games for Grades 4–6, with equipment, set-up, how to play, cues and safety." />
  <link rel="stylesheet" href="gotw-print.css" />
</head>
<!-- Generated by tools/build.js (tools/games-of-the-week.js) from games-of-the-week.json and the game cards. Do not edit by hand. -->
<body class="gp">
  <div class="gp-toolbar">
    <a href="games-of-the-week.html">← Games of the Week</a>
    <button type="button" id="gp-print">Print</button>
    <a href="${FILE}.pdf" download>Download printable (PDF)</a>
    <a href="${FILE}.docx" download>Download printable (Word)</a>
    <span id="gp-showing">All ${sheets.length} weeks: one page for Grades 1–3 and one for Grades 4–6 each week.</span>
    <a id="gp-all" href="games-of-the-week-print.html" hidden>Show all weeks</a>
  </div>
  <main class="gp-pages">
    <section class="gp-sheet gp-cover" id="contents">
      <header class="gp-band">
        <p class="gp-kicker">${e(printData.school)} · Grades 1–6</p>
        <h1>Games of the Week ${e(SY.calendar.label)}</h1>
        <p class="gp-unit">Mr. Fung · every school week: 3 games for Grades 1–3 and 3 for Grades 4–6 that fit the month’s unit · one page per grade band</p>
      </header>
      <table class="gp-contents">
        <tr class="gp-hrow"><th>Week</th><th>Dates</th>${BANDS.map((b) => `<th>${e(b.label)}</th>`).join("")}</tr>
${contents}
      </table>
      <p class="gp-foot">Every game is on the PE Playbook with its full card: ${e(SITE)}games-of-the-week.html</p>
    </section>
${sheets.map(sheetHtml).join("\n")}
  </main>
  <script src="gotw-print.js"></script>
</body>
</html>
`;

  const report = `games-of-the-week-data.js: ${weeks.length} school weeks, ${weeks.reduce((a, w) => a + w.bands.reduce((x, b) => x + b.picks.length, 0), 0)} picks (${BANDS.map((b) => b.label).join(" + ")}), ${breaks.length} breaks`;
  return { js, html, warnings, report, weeks, printHtml, printData };
};
